#!/usr/bin/env bash
# =============================================================================
# Container ports reachable from the home network and the VPN only, without
# naming this machine's address anywhere.
#
# Docker publishes a container port past UFW: its own rules come first. So a
# container published on every interface is reachable from wherever packets
# reach this machine, whatever `ufw status` says. Binding it to one address
# instead breaks the day the drive moves to hardware with another address.
#
# This adds a chain to Docker's DOCKER-USER, rebuilt at every boot and every
# Docker start from what the machine has THEN:
#
#   allowed   the subnet(s) on the interface holding the default route,
#             anything arriving on a WireGuard interface (wg*), container to
#             container traffic, and replies
#   dropped   everything else that would reach a container
#
#   /usr/local/sbin/docker-lan-guard              rebuilds the chain
#   /etc/systemd/system/docker-lan-guard.service  runs it, with Docker
#
# Host-network containers (Home Assistant, Uptime Kuma, wg-easy) never pass
# through DOCKER-USER: UFW still decides for those.
#
# Usage:
#   sudo add_docker_lan_guard.sh
#
# Safe to re-run: unchanged files are left alone, and the chain is rebuilt.
#
# Exit codes:
#   0  the chain is in place
#   1  something needed for the run is missing or failed
# =============================================================================

export DEBIAN_FRONTEND=noninteractive
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

print_header()  { printf "\n\033[36m=== %s ===\033[0m\n" "$1"; }
print_info()    { printf "\033[36mℹ️ %s\033[0m\n" "$1"; }
print_status()  { printf "\033[34m🔧 %s\033[0m\n" "$1"; }
print_success() { printf "\033[32m✅ %s\033[0m\n" "$1"; }
print_action()  { printf "\033[33m👉 %s\033[0m\n" "$1"; }
print_error()   { printf "\033[31m❌ %s\033[0m\n" "$1"; }

UNIT="docker-lan-guard.service"
UNIT_FILE="/etc/systemd/system/$UNIT"
GUARD="/usr/local/sbin/docker-lan-guard"
CHAIN="DOCKER-LAN-GUARD"

print_header "Container ports: home network and VPN only"

if [ "$EUID" -ne 0 ]; then
    print_error "This script needs root."
    print_action "Run it with: sudo bash $0"
    exit 1
fi

# --- Pre-flight --------------------------------------------------------------
ERRORS=()
command -v systemctl >/dev/null 2>&1 || ERRORS+=("No systemctl: this script expects systemd.")
command -v iptables >/dev/null 2>&1 || ERRORS+=("No iptables. Install it: sudo apt-get install -y iptables")
if ! command -v docker >/dev/null 2>&1; then
    ERRORS+=("Docker is not installed. Install it first: sudo bash $SCRIPT_DIR/add_docker.sh")
elif ! iptables -n -L DOCKER-USER >/dev/null 2>&1; then
    ERRORS+=("Docker's DOCKER-USER chain is missing, so Docker is not running. Check it: sudo systemctl status docker")
fi
if [ -z "$(ip -4 route show default 2>/dev/null)" ]; then
    ERRORS+=("No default route, so the home network cannot be found. Check the network: ip -4 route")
fi
if [ ${#ERRORS[@]} -gt 0 ]; then
    print_error "Pre-flight failed, nothing was changed:"
    for e in "${ERRORS[@]}"; do print_error "  $e"; done
    exit 1
fi
print_success "Pre-flight passed."

# --- The script the unit runs ------------------------------------------------
# Quoted heredoc: everything below is the guard's own code, run at boot.
NEW_GUARD="$(cat <<'EOF'
#!/usr/bin/env bash
# Generated by add_docker_lan_guard.sh. The next run overwrites it.
# Rebuilds DOCKER-LAN-GUARD from the addresses this machine has now.
CHAIN="DOCKER-LAN-GUARD"

lan_dev() {
    ip "-$1" route show default 2>/dev/null \
        | awk '{for (i = 1; i < NF; i++) if ($i == "dev") { print $(i + 1); exit }}'
}

# A boot can get here before DHCP has answered: wait for it, then fail closed.
for _ in $(seq 1 60); do
    [ -n "$(lan_dev 4)" ] && break
    sleep 1
done

rebuild() {
    local ipt="$1" fam="$2" dev net
    "$ipt" -n -L DOCKER-USER >/dev/null 2>&1 || return 0
    "$ipt" -N "$CHAIN" 2>/dev/null || "$ipt" -F "$CHAIN"
    "$ipt" -A "$CHAIN" -m conntrack --ctstate RELATED,ESTABLISHED -j RETURN
    "$ipt" -A "$CHAIN" -i docker0 -j RETURN
    "$ipt" -A "$CHAIN" -i br+ -j RETURN
    "$ipt" -A "$CHAIN" -i wg+ -j RETURN
    dev="$(lan_dev "$fam")"
    if [ -n "$dev" ]; then
        for net in $(ip "-$fam" route show dev "$dev" 2>/dev/null \
                | awk '$1 != "default" && $1 !~ /^(multicast|broadcast|local)$/ { print $1 }' | sort -u); do
            "$ipt" -A "$CHAIN" -i "$dev" -s "$net" -j RETURN
            echo "IPv$fam allowed: $net on $dev"
        done
        [ "$fam" = 6 ] && "$ipt" -A "$CHAIN" -i "$dev" -s fe80::/10 -j RETURN
    else
        echo "IPv$fam: no default route, so only the VPN and containers are allowed"
    fi
    "$ipt" -A "$CHAIN" -j DROP
    "$ipt" -C DOCKER-USER -j "$CHAIN" 2>/dev/null || "$ipt" -I DOCKER-USER -j "$CHAIN"
}

rebuild iptables 4
command -v ip6tables >/dev/null 2>&1 && rebuild ip6tables 6
[ -n "$(lan_dev 4)" ]
EOF
)"

NEW_UNIT="$(cat <<EOF
# Generated by add_docker_lan_guard.sh. The next run overwrites it.
[Unit]
Description=Container ports reachable from the home network and VPN only
After=docker.service network-online.target
Wants=network-online.target
# Docker rebuilds its own chains on start, so this follows it.
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=${GUARD}
Restart=on-failure
RestartSec=30

[Install]
WantedBy=docker.service multi-user.target
EOF
)"

CHANGED=0
for pair in "$GUARD|$NEW_GUARD|0755" "$UNIT_FILE|$NEW_UNIT|0644"; do
    path="${pair%%|*}"; rest="${pair#*|}"
    body="${rest%|*}"; mode="${rest##*|}"
    if [ -f "$path" ] && [ "$(cat "$path")" = "$body" ]; then
        print_success "Unchanged: $path"
        continue
    fi
    printf '%s\n' "$body" > "$path"
    chmod "$mode" "$path"
    print_success "Wrote $path"
    CHANGED=1
done
[ "$CHANGED" -eq 1 ] && systemctl daemon-reload

if ! out="$(systemctl enable "$UNIT" 2>&1)"; then
    print_error "Could not enable $UNIT, so the chain would be gone after a reboot."
    printf '%s\n' "$out"
    exit 1
fi
if ! systemctl restart "$UNIT"; then
    print_error "The guard did not apply. Why: journalctl -u $UNIT -n 20"
    exit 1
fi
journalctl -u "$UNIT" -n 10 --no-pager -o cat 2>/dev/null | grep -E "allowed|no default" \
    | while IFS= read -r line; do print_status "$line"; done
print_status "Also allowed: WireGuard (wg*), container to container, replies."

echo ""
print_success "Container ports answer the home network and the VPN only."
print_info "Rules: sudo iptables -S $CHAIN"
