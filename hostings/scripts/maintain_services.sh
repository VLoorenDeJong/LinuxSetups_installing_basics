    else
        apply_skipped "add_postfix.sh" "not found next to this script"
    fi
elif mail_stand_down_owed; then
    if [ -f "$SCRIPT_DIR/add_postfix.sh" ]; then
        print_info "No mailbox rows, but the mail configs still name a certificate."
        print_info "Running the mail stack so it stands down and releases the lineage."
        run_step add_postfix.sh
