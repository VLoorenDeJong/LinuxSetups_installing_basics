#!/usr/bin/env bash
# A redraw needs a terminal. In a Jenkins log \r is not a carriage return, so
# every update lands as its own line and \033[K blanks it: seventeen units
# printed one line of text and sixteen empty ones. Silent there instead, since
# each of these loops already prints a summary when it finishes.
redraw() { [ -t 1 ] || return 0; printf "$@"; }
set -e

# -d / --debug: trace every command. Stripped from "$@" so it never reaches the
# script's own argument parsing.
DEBUG_MODE=0
_dbg_args=()
for _a in "$@"; do
    case "$_a" in
        -d|--debug) DEBUG_MODE=1 ;;
        *)          _dbg_args+=("$_a") ;;
    esac
done
set -- ${_dbg_args+"${_dbg_args[@]}"}
unset _a _dbg_args
[ "$DEBUG_MODE" = "1" ] && set -x

# =============================================================================
# Make this machine match /etc/hostings/hostings.conf.
#
#   ./maintain_services.sh            check, report, then apply
#   ./maintain_services.sh --check    check and report, change nothing
#   ./maintain_services.sh --prune    also delete what the config no longer lists
#   ./maintain_services.sh --verify   only check that every site answers
#
# This is layer 3 of the three-layer design: the generators are layer 1 and
# stay runnable on their own, and this calls them rather than replacing them.
# Nothing here duplicates what they do; it adds the three things they cannot do
# individually.
#
# 1. PRE-FLIGHT, ALWAYS
#
# The whole config is validated before the first write. A script that fails
# halfway leaves a machine in a state nobody designed, and that state is always
# harder to diagnose than a refusal.
#
# Errors block: a duplicate port or a missing credential file means the run
# cannot succeed. Warnings do not: DNS that does not resolve yet is worth
# knowing, but the rest of the run is still correct. If warnings blocked, a
# machine with one un-pointed record could never be configured at all.
#
# 2. DRIFT REPORT, BEFORE ACTING
#
#   ADD      the config says this should exist, the machine has no such thing
#   UPDATE   it exists, but differs from what the config would generate
#   OK       machine matches config
#   ORPHAN   on the machine, carries our generated header, no longer in config
#
# Printed before anything changes, so a re-run showing all OK is how you know it
# is genuinely a no-op rather than something you have to trust.
#
# 3. PRUNE, ONLY WHEN ASKED
#
# Orphans are reported by default and deleted only with --prune, and only ever
# files carrying "Generated by ... from hostings.conf". Anything a human wrote
# is invisible to this script by definition. That rule is what keeps a year of
# hand-written vhosts under backup_files/ safe from a --prune run.
# =============================================================================

export DEBIAN_FRONTEND=noninteractive

# --- Inline utility functions (always defined, no sourcing required) ---
print_status() {
    printf "\033[34m🔧 %s\033[0m\n" "$1"
}

print_success() {
    printf "\033[32m✅ %s\033[0m\n" "$1"
}

print_warning() {
    printf "\033[33m⚠️ %s\033[0m\n" "$1"
}

# Yellow means "this needs you", never "warning": a question, an instruction,
# a URL to go and open. Anything the reader cannot act on is cyan.
# Conventions: bash-installer-conventions.md.
print_action()  { printf "\033[33m👉 %s\033[0m\n" "$1"; }
print_info()    { printf "\033[36mℹ️ %s\033[0m\n" "$1"; }

print_error() {
    printf "\033[31m❌ %s\033[0m\n" "$1"
}

print_header() {
    printf "\n\033[36m=== %s ===\033[0m\n" "$1"
}

# Watch-only spinner: shows the command is alive but never signals it. Nothing
# here is safe to kill halfway, so there is no timeout and no SIGTERM.
#
# Silent when stdout is not a terminal. check_hostings.sh captures this script
# into the file the hosting manager displays, and carriage returns in a report
# are noise nobody can read.
show_spinner_watch_only() {
    local message="$1"
    shift
    if [ ! -t 1 ]; then "$@"; return $?; fi

    local frames=('⠋' '⠙' '⠹' '⠸' '⠼' '⠴' '⠦' '⠧' '⠇' '⠏')
    "$@" &
    local cmd_pid=$! tick=0
    while kill -0 "$cmd_pid" 2>/dev/null; do
        redraw '\r\033[K\033[34m%s %s\033[0m' "${frames[tick % 10]}" "$message"
        tick=$((tick + 1))
        sleep 0.2 || { printf "\n\033[31m❌ Progress loop aborted — sleep failed (filesystem trouble?)\033[0m\n"; break; }
    done
    local exit_code=0
    wait "$cmd_pid" || exit_code=$?
    redraw '\r\033[K'
    return $exit_code
}

# Wrapped commands whose output is needed write it to a file, so the spinner
# keeps the terminal to itself.
list_hosts_from() {
    LIST_HOSTS=1 SITES_CONF="$SITES_CONF" bash "$1" >"$2" 2>/dev/null || printf '' >"$2"
}

usage() {
    echo "Usage: $0 [--apply] [--check] [--prune] [--changed] [--only-row NAME]" >&2
    echo "" >&2
    echo "  --apply   make the machine match the config. The default, and the" >&2
    echo "            spelling a sudoers rule can match: a rule ending in '*'" >&2
    echo "            never matches a command run with no arguments at all." >&2
    echo "  --check   validate and report, change nothing" >&2
    echo "  --prune   delete generated files the config no longer lists" >&2
    echo "  --verify  only check that every published site answers, change nothing" >&2
    echo "  --changed write only the rows the last publish changed, worked out" >&2
    echo "            by changed_rows.sh from git. Falls back to writing" >&2
    echo "            everything whenever it cannot narrow it honestly." >&2
    echo "  --only-row NAME" >&2
    echo "            write only this row's unit, vhost and certificate." >&2
    echo "            Comma separated for several. The drift report still" >&2
    echo "            covers everything, so orphans stay visible." >&2
    echo "" >&2
    echo "Environment:" >&2
    echo "  SITES_CONF   override the config location" >&2
    echo "  CERT_EMAIL   passed through to add_site_certificates.sh" >&2
    echo "  ONLY_ROWS    same as --only-row" >&2
    exit 1
}

CHECK_ONLY=0
PRUNE=0
VERIFY_ONLY=0
CHANGED_ONLY=0
NO_ROWS_CHANGED=0
ONLY_ROWS="${ONLY_ROWS:-}"
while [ $# -gt 0 ]; do
    case "$1" in
        --apply)  shift ;;
        --check)  CHECK_ONLY=1; shift ;;
        --prune)  PRUNE=1; shift ;;
        --verify) VERIFY_ONLY=1; shift ;;
        --changed) CHANGED_ONLY=1; shift ;;
        --only-row)   ONLY_ROWS="$2"; shift 2 ;;
        --only-row=*) ONLY_ROWS="${1#--only-row=}"; shift ;;
        -h|--help) usage ;;
        *) print_error "Unknown option: $1"; usage ;;
    esac
done

# --only-row and --prune used to be refused together, because narrowing the
# WRITING once risked narrowing the drift report with it, and a narrowed report
# calls every untouched site an orphan.
#
# report_drift.sh removes that risk by construction: it reads the whole config
# and does not know ONLY_ROWS exists. The two can now run in one pass, which is
# what "apply my change, and clean up what my change orphaned" needs.


if [ "$EUID" -ne 0 ]; then
    print_error "This script requires sudo privileges to run properly."
    print_action "Please run with: sudo $0"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
. "$SCRIPT_DIR/config.sh" 2>/dev/null \
    || . /usr/local/lib/linuxbasics/hostings/scripts/config.sh 2>/dev/null \
    || conf_active() { printf '%s/hostings.conf' "$1"; }
SITES_CONF="${SITES_CONF:-$(conf_active "/etc/hostings")}"

if [ ! -f "$SITES_CONF" ]; then
    print_error "Config not found: $SITES_CONF"
    exit 1
fi
# --changed asks changed_rows.sh which rows the last publish moved. Every
# uncertainty there answers "all of them": exit 2 means it could not narrow it
# honestly, and a narrow answer that is wrong writes nothing where something
# was needed, which is the failure nobody notices until a site is down.
#
# THE BASE IS THE LAST COMMIT THIS MACHINE APPLIED, not HEAD~1. Measured
# 2026-09-12: a console save committed a row as Enabled = no, the tree then
# caught up over five commits, and changed_rows.sh's default HEAD~1 diffed the
# newest commit instead. It reported nothing changed, the write steps were
# skipped, and the run still printed "Machine matches" over a row whose unit was
# still active. A narrow answer that is wrong is exactly what the comment above
# warns about, and the default base was producing one.
#
# No record means no honest way to narrow, so every row is written.
APPLIED_MARK="/var/lib/hosting-manager/last-applied-commit"
if [ "$CHANGED_ONLY" -eq 1 ]; then
    _cr="$SCRIPT_DIR/changed_rows.sh"
    if [ ! -f "$_cr" ]; then
        print_info "changed_rows.sh is not next to this script, so every row is written."
    else
        _since=""
        if [ -r "$APPLIED_MARK" ]; then
            _since="$(tr -d ' \t\r\n' < "$APPLIED_MARK" 2>/dev/null || true)"
            if [ -n "$_since" ] \
               && ! git -C "$REPO_ROOT" rev-parse --verify --quiet "$_since^{commit}" >/dev/null 2>&1; then
                print_info "The last applied commit ${_since:0:7} is not in this tree, so every row is written."
                _since=""
            fi
        fi
        set +e
        if [ -n "$_since" ]; then
            print_info "Comparing against the last commit this machine applied, ${_since:0:7}."
            _rows="$(SITES_CONF="$SITES_CONF" SINCE="$_since" bash "$_cr")"
        else
            # Exit 2 downstream is "could not narrow honestly", which writes
            # every row. That is the right answer for a machine that has never
            # recorded an apply.
            _rows=""
            false
        fi
        _rc=$?
        set -e
        if [ "$_rc" -eq 0 ] && [ -n "$_rows" ]; then
            # A row the diff names but the config no longer holds was deleted.
            # That is a real change and its work is the prune, not a write, so
            # it is dropped from the scope rather than failing check_config's
            # typo guard, which cannot tell the two apart. The row test matches
            # changed_rows.sh: a setting line carries '=' before the first pipe
            # and a mailbox row is not a service row, so neither can claim a
            # deleted row's name.
            _kept=(); _gone=()
            while read -r _n; do
                [ -z "$_n" ] && continue
                set +e
                awk -F'|' -v n="$_n" '
                    /^[[:space:]]*#/ { next }
                    NF > 1 {
                        k = $1; gsub(/^[[:space:]]+|[[:space:]]+$/, "", k)
                        if (k ~ /=/ || k == "mailbox") next
                        gsub(/^[[:space:]]+|[[:space:]]+$/, "", $2)
                        if ($2 == n) found = 1
                    }
                    END { exit !found }' "$SITES_CONF"
                _look=$?
                set -e
                case "$_look" in
                    0) _kept+=("$_n") ;;
                    1) _gone+=("$_n") ;;
                    *) print_error "Could not read $SITES_CONF while checking row '$_n'. Nothing was changed."
                       exit 1 ;;
                esac
            done <<< "$_rows"
            if [ "${#_gone[@]}" -gt 0 ]; then
                print_info "No longer in the config, so not written: $(printf '%s,' "${_gone[@]}" | sed 's/,$//')"
            fi
            if [ "${#_kept[@]}" -gt 0 ]; then
                ONLY_ROWS="$(printf '%s,' "${_kept[@]}" | sed 's/,$//')"
                print_status "Changed rows: $ONLY_ROWS"
            elif [ "$PRUNE" -eq 1 ]; then
                NO_ROWS_CHANGED=1
                print_info "Every changed row was a removal, so nothing is written and the orphans are pruned."
            else
                NO_ROWS_CHANGED=1
                print_info "Every changed row was a removal, so nothing is written. Orphans are reported; add --prune to delete them."
            fi
        elif [ "$_rc" -eq 0 ]; then
            # An empty ONLY_ROWS means "every row" everywhere downstream, so
            # saying nothing here wrote all of them. Nothing changed means
            # nothing is written; orphans are still pruned, because they come
            # from the machine rather than from the diff.
            NO_ROWS_CHANGED=1
            print_status "No row changed since the previous commit, so nothing is written."
        else
            print_status "Could not narrow this to the rows that changed, so every row is written."
        fi
    fi
fi

export ONLY_ROWS

# -----------------------------------------------------------------------------
# Config readers. Duplicated verbatim rather than sourced, so this script stays
# runnable on its own on a machine that has only this file copied to it.
# -----------------------------------------------------------------------------
# Read once, in bash, rather than five forks per key.
#
# The cache below already meant one key was read once. The first read still
# cost sed, head, echo, sed and xargs: five processes, about 4ms each on this
# hardware, for one line of a file that was going to be read sixty times over.
# Measured 2026-08-24 with strace: 108 seds and 108 echos in a 4 second check.
#
# One pass loads every setting. A row line is not a setting: it holds pipes and
# no leading KEY=, and the pattern below cannot match it. First occurrence
# wins, which is what `head -n 1` did.
declare -A _CONF_CACHE=()
_CONF_LOADED=0
_conf_load() {
    local line key value
    [ "$_CONF_LOADED" = "1" ] && return 0
    _CONF_LOADED=1
    [ -f "$SITES_CONF" ] || return 0

    while IFS= read -r line || [ -n "$line" ]; do
        [[ "$line" =~ ^[[:space:]]*([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*=(.*)$ ]] || continue
        key="${BASH_REMATCH[1]}"
        [ -n "${_CONF_CACHE[$key]+set}" ] && continue
        # A CRLF config leaves a carriage return on the end of the value, and
        # the two trims below only remove whitespace.
        value="${BASH_REMATCH[2]//$'\r'/}"
        value="${value%%#*}"
        value="${value#"${value%%[![:space:]]*}"}"
        value="${value%"${value##*[![:space:]]}"}"
        _CONF_CACHE[$key]="$value"
    done < "$SITES_CONF"
}

# Filled at the top level by the call below, never first from in here.
#
# conf_get is always called as $(conf_get ...), and a command substitution is a
# subshell. A cache filled inside one dies with it, which is why the
# memoisation this replaces never once served a second caller: every call took
# the slow path and nobody noticed, because the slow path was only five forks.
# Loading in the parent means each subshell inherits an array already full.
conf_get() {
    local key="$1" default="$2" value
    _conf_load
    value="${_CONF_CACHE[$key]:-}"
    echo "${value:-$default}"
}

_conf_load

conf_rows() {
    # One awk pass. A bash read loop over the whole file cost 0.2s per call.
    # A SETTING line is skipped even when it holds pipes, as PANEL lines do.
    awk '{ sub(/#.*/, "") } /^[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*=/ { next } /\|/' "$SITES_CONF"
}

# Does this row exist in this environment?
#
# The Envs field is empty for almost everything, meaning all of them. It exists
# because a test environment proves a build runs, which needs one instance of an
# application rather than one per customer: the four progress tenants are live
# only, and a single row covers test.
row_in_env() {
    local list="$1" env="$2" e
    list="$(echo "$list" | xargs)"
    [ -z "$list" ] || [ "$list" = "-" ] && return 0
    IFS=',' read -r -a _re <<< "$list"
    for e in "${_re[@]}"; do
        [ "$(echo "$e" | xargs)" = "$env" ] && return 0
    done
    return 1
}

# One place that decides what counts as yes. Accepts y, yes, true and 1 in any
# case; everything else, including empty and a dash, is no. Written once rather
# than as a case pattern at each site, because a value accepted in one script
# and rejected in another is the kind of inconsistency nobody finds quickly.
is_yes() {
    local v="$1"
    v="${v#"${v%%[![:space:]]*}"}"
    v="${v%"${v##*[![:space:]]}"}"
    case "${v,,}" in
        y|yes|true|1) return 0 ;;
        *)            return 1 ;;
    esac
}

# Is this row protected in this environment?
#
# Duplicated verbatim from add_app_vhosts.sh, which is the rule for this
# repo: every script stays runnable on a machine that has only that one file.
# The duplication is safe because this script cross-checks the generators
# against each other, so a copy that drifts is reported rather than discovered.
#
#   live:no, test:yes    per environment
#   yes / no             every environment
#
# An environment the row does not mention is protected, so a test copy cannot be
# published open by accident.
auth_in_env() {
    local spec="$1" env="$2" part k v
    spec="$(echo "$spec" | xargs)"

    case "$spec" in
        *:*) ;;
        *)   is_yes "$spec" && return 0 || return 1 ;;
    esac

    IFS=',' read -r -a _ae <<< "$spec"
    for part in ${_ae+"${_ae[@]}"}; do
        k="$(trim "${part%%:*}")"
        v="$(trim "${part#*:}")"
        if [ "$k" = "$env" ]; then
            is_yes "$v" && return 0 || return 1
        fi
    done

    # This script calls the first environment DEFAULT_ENV where the generator
    # calls it DEFAULT_PUBLISH. Same value, different name, so the copy is not
    # quite verbatim after all.
    [ "$env" = "$DEFAULT_ENV" ] && return 1
    return 0
}

# A field holding a single dash means empty. `| | |` cannot be counted by eye.
trim() {
    # Pure bash: no echo, no xargs. This is called once per field per row per
    # environment, and each fork costs more than the work it does.
    local v="$1"
    v="${v#"${v%%[![:space:]]*}"}"
    v="${v%"${v##*[![:space:]]}"}"
    [ "$v" = "-" ] && v=""
    printf '%s' "$v"
}

