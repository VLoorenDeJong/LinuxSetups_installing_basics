# THE MAIL STACK, which this chain has never run. Until 2026-09-06 the mail
# scripts existed only in add_mail_stack.sh at install time, so a mailbox added
# from the console became a config row and nothing else: no Postfix domain, no
# delivery entry, no Dovecot account, and the job reported SUCCESS over it.
#
# add_postfix.sh, not add_dovecot.sh, and only that one: it chains add_dovecot.sh
# itself at its end, so calling both would run Dovecot twice.
#
# Outside the "no row changed" guard for the same reason previews and panels are:
# a mailbox row carries no vhost and no unit, so a change to one leaves every
# other check seeing nothing to do.
#
# Skipped when no mailbox row exists AND the mail configs no longer name a
# Let's Encrypt lineage. Running the mail stack on every apply of a machine that
# serves no mail is work nobody asked for.
#
# But "no mailbox rows" was the whole condition until 2026-09-07, and that is
# the one case where the scripts have work to do. Deleting the last mailbox row
# leaves Dovecot and Postfix still naming mail.<domain>, so the prune refuses to
# remove the lineage and the drift report calls it an orphan for ever. Both
# scripts stand down to the self-signed pair at zero rows, which b06fee1 built
# on 2026-09-06 for exactly this, and this guard is what stopped it running.
#
# Measured 2026-09-07: three mailbox rows deleted, then Fix drift pressed twice.
# Both times the full apply skipped add_postfix.sh and the same three orphans
# came back, with no button able to clear them.
mail_stand_down_owed() {
    grep -qs -- '/etc/letsencrypt/live/' \
        /etc/postfix/main.cf /etc/dovecot/conf.d/*.conf 2>/dev/null
}

