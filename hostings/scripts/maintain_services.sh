BASE_DOMAIN="$(conf_get BASE_DOMAIN "")"
[ -z "$BASE_DOMAIN" ] && err "No BASE_DOMAIN in $SITES_CONF"

IFS=',' read -r -a ALL_ENVS <<< "$(conf_get ENVS live)"
for i in "${!ALL_ENVS[@]}"; do ALL_ENVS[$i]="$(trim "${ALL_ENVS[$i]}")"; done
DEFAULT_ENV="${ALL_ENVS[0]}"

IFS=',' read -r -a PUBLISH_ENVS <<< "$(conf_get PUBLISH_ENVS "$(conf_get ENVS live)")"
for i in "${!PUBLISH_ENVS[@]}"; do PUBLISH_ENVS[$i]="$(trim "${PUBLISH_ENVS[$i]}")"; done

AUTH_USER_FILE="$(conf_get AUTH_USER_FILE /etc/apache2/.htpasswd-progress)"
AUTH_SESSION_KEY_FILE="$(conf_get AUTH_SESSION_KEY_FILE /etc/apache2/session-crypto.key)"

AVAILABLE_DIR="/etc/apache2/sites-available"
UNIT_DIR="/etc/systemd/system"
GENERATED_MARK="from /etc/hostings/hostings.conf"

# =============================================================================
# Verify every published site actually answers.
#
# The check lives in verify_sites.sh, one question per script, and that file
# carries the reasoning. This is the call, kept so --verify and the end of an
# apply behave as they always did.
# A missing file is reported, never silently skipped: a check that did not run
# must not read as a check that passed.
#
# Given `scoped`, it asks only the rows this run wrote. After an apply that is
# the honest question: the other sites were not touched. `--verify` on its own
# asks about all of them, which is why it is the caller that decides.
verify_sites() {
    local script="$SCRIPT_DIR/verify_sites.sh"
    if [ ! -f "$script" ]; then
        print_info "verify_sites.sh is not next to this script, so no site was verified."
        return 0
    fi
    local only=""
    [ "${1:-}" = "scoped" ] && only="$ONLY_ROWS"
    ONLY_ROWS="$only" SITES_CONF="$SITES_CONF" bash "$script"
}

# --verify answers one question: does every published site answer? It needs the
# config read and nothing else, so it skips validation, drift and the
# generators entirely.
if [ "$VERIFY_ONLY" -eq 1 ]; then
    # With --changed it asks only the rows the last publish moved, so the job's
    # own Verify stage does not re-ask all 26 hostnames after the apply already
    # asked the handful that changed.
    if [ "$CHANGED_ONLY" -eq 1 ]; then
        if [ "$NO_ROWS_CHANGED" -eq 1 ]; then
            print_status "No row changed, so there is nothing to ask about."
            exit 0
        fi
        verify_sites scoped
    else
        verify_sites
    fi
    exit $?
fi

print_header "Pre-flight"

# Two questions, two scripts, and they do not depend on each other: one reads
# the config, the other asks the generators. Started together and waited for,
# because the second is the slow one and nothing in the first is its input.
FLAGS_FILE="$(mktemp)"
CONFIG_LOG="$(mktemp)"
GEN_LOG="$(mktemp)"
REQ_FILE="$(mktemp)"
DRIFT_FILE="$(mktemp)"
trap 'rm -f "$FLAGS_FILE" "$CONFIG_LOG" "$GEN_LOG" "$DRIFT_FILE" "$REQ_FILE"' EXIT

need_script() {
    [ -f "$SCRIPT_DIR/$1" ] && return 0
    print_error "$1 is not next to this script, so the pre-flight cannot run."
    exit 1
}
need_script check_config.sh
need_script check_generators_agree.sh

set +e
FLAGS_OUT="$FLAGS_FILE" ONLY_ROWS="$ONLY_ROWS" SITES_CONF="$SITES_CONF" \
    bash "$SCRIPT_DIR/check_config.sh" >"$CONFIG_LOG" 2>&1 &
config_pid=$!
REQUESTED_OUT="$REQ_FILE" SITES_CONF="$SITES_CONF" \
    bash "$SCRIPT_DIR/check_generators_agree.sh" >"$GEN_LOG" 2>&1 &
gen_pid=$!
wait "$config_pid"; config_rc=$?
wait "$gen_pid";    gen_rc=$?
set -e

cat "$CONFIG_LOG"
cat "$GEN_LOG"

# What the config was found to need, read rather than worked out again.
NEEDS_CERT=0
HAVE_CERTBOT=0
ROW_COUNT=0
if [ -s "$FLAGS_FILE" ]; then
    # shellcheck disable=SC1090
    . "$FLAGS_FILE"
fi

if [ "$config_rc" -ne 0 ] || [ "$gen_rc" -ne 0 ]; then
    echo ""
    print_error "Pre-flight failed. Nothing was changed."
    exit 1
fi

print_success "Pre-flight passed: $ROW_COUNT rows, no errors."

# =============================================================================
# 3. Drift: what the config says, against what is on the machine
#
# Worked out by report_drift.sh, which reports and never writes. The list it
# leaves in DRIFT_FILE is what the pruner consumes, so the deciding happens
# once and the deleting happens somewhere else.
# =============================================================================

DRIFT_SCRIPT="$SCRIPT_DIR/report_drift.sh"
if [ ! -f "$DRIFT_SCRIPT" ]; then
    print_error "report_drift.sh is not next to this script, so drift cannot be reported."
    exit 1
fi
# The hostname list comes from the pre-flight rather than being asked for
# again: that question costs a whole pass over the config, and it has just
# been answered.
# ONLY_ROWS cleared, and stated rather than relied on: the drift report must see
# every row, because an orphan is by definition something no row asks for, and
# --prune acts on that list.
# The tree check below only reads git, so it runs while the drift is worked out
# and is printed after it, in the same place as before.
TREES_SCRIPT="$SCRIPT_DIR/check_tree_versions.sh"
TREES_LOG="$(mktemp)"
trap 'rm -f "$FLAGS_FILE" "$CONFIG_LOG" "$GEN_LOG" "$DRIFT_FILE" "$REQ_FILE" "$TREES_LOG"' EXIT
trees_pid=""
if [ -f "$TREES_SCRIPT" ]; then
    bash "$TREES_SCRIPT" >"$TREES_LOG" 2>&1 &
    trees_pid=$!
fi

DRIFT_OUT="$DRIFT_FILE" REQUESTED_HOSTS_FILE="$REQ_FILE" ONLY_ROWS= \
    SITES_CONF="$SITES_CONF" bash "$DRIFT_SCRIPT"

# Which commit is each copy of the repository on this machine running?
#
# A different question from drift, and it belongs beside it because it is the
# one that makes drift trustworthy: the answer above was produced by whatever
# code this tree happens to hold, and on 2026-08-27 two of the three trees were
# four commits behind with nothing anywhere saying so.
#
# Skipped in silence when the script is not beside this one, so a copy of
# maintain_services.sh on its own still runs and reports one question less. It
# must never fail the check: it reads and nothing more, and a check that goes
# red because a reporter tripped is a check that gets ignored.
if [ -n "$trees_pid" ]; then
    trees_rc=0
    wait "$trees_pid" || trees_rc=$?
    cat "$TREES_LOG"
    [ "$trees_rc" -eq 0 ] || print_info "The tree version check did not finish. Drift above is unaffected."
fi

ORPHAN_COUNT="$(grep -c '^ORPHAN ' "$DRIFT_FILE" || true)"

if [ "$CHECK_ONLY" -eq 1 ]; then
    echo ""
    print_success "--check: nothing was changed."
    if [ "$ORPHAN_COUNT" -gt 0 ]; then
        print_action "Run with --prune to delete the orphans above."
        if grep -q '^ORPHAN cert ' "$DRIFT_FILE"; then
            if [ "$HAVE_CERTBOT" -eq 1 ]; then
                print_info "A cert line means the certificate itself is deleted, not just a file."
            else
                print_info "A cert line is reported only: certbot is missing, so nothing would delete it."
            fi
        fi
    fi
    exit 0
fi


# =============================================================================
# 4. Apply, by calling layer 1. Nothing here duplicates what they do.
# =============================================================================
# What each generator did, so the end of the run says it in one place.
#
# This already named the failing script and stopped, which is the important
# half. What it did not say is what had ALREADY run by then, and an apply that
# stops in the middle leaves exactly that question: the operator sees one red
# line and a machine in an unknown state. Same shape as the create's report,
# and it is written where the console can read it. The owner, 2026-09-03.
APPLY_NAMES=()
APPLY_STATES=()
APPLY_NOTES=()

apply_report() {
    [ ${#APPLY_NAMES[@]} -eq 0 ] && return 0
    echo ""
    print_header "What the apply did"
    local i mark
    for i in "${!APPLY_NAMES[@]}"; do
        case "${APPLY_STATES[$i]}" in
            ok)     mark="\033[32m  ok     \033[0m" ;;
            failed) mark="\033[31m  FAILED \033[0m" ;;
            *)      mark="\033[34m  skipped\033[0m" ;;
        esac
        printf "%b%s\n" "$mark" " ${APPLY_NAMES[$i]}"
        [ -n "${APPLY_NOTES[$i]}" ] && printf "\033[36m           %s\033[0m\n" "${APPLY_NOTES[$i]}"
    done

    local f="/var/lib/hosting-manager/last-apply.json" tmp
    [ -d /var/lib/hosting-manager ] || return 0
    tmp="$(mktemp)"
    {
        printf '{"when":"%s","steps":[' "$(date -Is)"
        for i in "${!APPLY_NAMES[@]}"; do
            [ "$i" -gt 0 ] && printf ','
            printf '{"name":"%s","state":"%s","note":"%s"}' \
                "${APPLY_NAMES[$i]//\"/}" "${APPLY_STATES[$i]}" \
                "$(printf '%s' "${APPLY_NOTES[$i]}" | sed 's/\\/\\\\/g; s/"/\\"/g')"
        done
        printf ']}\n'
    } > "$tmp"
    install -m 0644 -o root -g root "$tmp" "$f" 2>/dev/null || true
    rm -f "$tmp"
}

apply_skipped() {
    APPLY_NAMES+=("$1"); APPLY_STATES+=("skipped"); APPLY_NOTES+=("${2:-}")
}

run_step() {
    local script="$1"; shift
    local path="$SCRIPT_DIR/$script"
    local label="$script${1:+ $*}"
    if [ ! -f "$path" ]; then
        APPLY_NAMES+=("$label"); APPLY_STATES+=("failed")
        APPLY_NOTES+=("not found next to this script")
        print_error "$script not found next to this script."
        apply_report
        exit 1
    fi
    print_header "$script"
    if ! bash "$path" "$@"; then
        APPLY_NAMES+=("$label"); APPLY_STATES+=("failed"); APPLY_NOTES+=("exited non-zero")
        print_error "$script failed. Stopping before anything else runs."
        # Printed BEFORE exiting, or the run that most needs the summary is the
        # one that never gets it.
        apply_report
        exit 1
    fi
    APPLY_NAMES+=("$label"); APPLY_STATES+=("ok"); APPLY_NOTES+=("")
}

# -----------------------------------------------------------------------------
# Self-healing: rows whose machine state is missing, whatever the diff said.
#
# --changed asks git which rows moved, and that answer can be right and still
# leave a row unbuilt. Measured 2026-09-04: three applications were created from
# the console and the applies reported "no row changed since the previous
# commit", because the console publishes the config and then pushes a second
# write-back commit, so each apply diffed the wrong pair. A row created from an
# EXISTING repository got no Jenkins jobs, no unit and no restart grant, and
# could never deploy.
#
# So the diff decides what to REWRITE, and this decides what is MISSING. A row
# with no unit joins the scope whatever git said: a missing unit is not an
# opinion.
# -----------------------------------------------------------------------------
HEAL_ROWS=()

# True when any existing unit of the row is enabled or running while the row
# says no, or disabled while it says yes. A missing environment unit is the ADD
# path's job.
unit_state_differs() {
    local name="$1" want="$2" e sfx unit state
    for e in $(conf_get ENVS live | tr ',' ' '); do
        sfx="$(conf_get "${e^^}_UNIT_SUFFIX" "")"
        unit="app-${name}${sfx}.service"
        [ -f "/etc/systemd/system/$unit" ] || continue
        state="$(systemctl is-enabled "$unit" 2>/dev/null || true)"
        if [ "$want" = "no" ]; then
            [ "$state" = "enabled" ] && return 0
            case "$(systemctl is-active "$unit" 2>/dev/null)" in
                active|activating|reloading) return 0 ;;
            esac
        else
            [ "$state" = "disabled" ] && return 0
        fi
    done
    return 1
}

NEED_JOBS=0
NEED_GRANT=0
JENKINS_JOBS_DIR="${JENKINS_JOBS_DIR:-/var/lib/jenkins/jobs}"
DEPLOY_SUDOERS="${DEPLOY_SUDOERS:-/etc/sudoers.d/010_jenkins-deploy}"

while IFS='|' read -r _t _n _p _pa _su _ds _op _au _repo _br _envs _aus _rm _rt _en _rest; do
    _t="$(printf '%s' "$_t" | tr -d ' \r')"
    _n="$(printf '%s' "$_n" | tr -d ' \r')"
    _repo="$(printf '%s' "$_repo" | tr -d ' \r')"
    _en="$(printf '%s' "$_en" | tr -d ' \r' | tr '[:upper:]' '[:lower:]')"
    [ -z "$_n" ] && continue
    case "$_t" in *=*) continue ;; esac

    if [ "$_t" = "app" ] && [ ! -f "/etc/systemd/system/app-${_n}.service" ]; then
        HEAL_ROWS+=("$_n")
        NEED_GRANT=1
        print_info "$_n has no unit on this machine, so it is written whatever the diff said."
    elif [ "$_t" = "app" ] && unit_state_differs "$_n" "$_en"; then
        # Measured 2026-09-15: a row disabled on 2026-09-12 kept its unit running
        # for three days, because no later diff named it.
        HEAL_ROWS+=("$_n")
        print_info "$_n has a unit whose enabled or running state does not match the config, so it is written whatever the diff said."
    elif [ "$_t" = "app" ] && [ -f "$DEPLOY_SUDOERS" ] && ! grep -q "app-${_n}\.service" "$DEPLOY_SUDOERS"; then
        NEED_GRANT=1
        print_info "$_n has a unit that jenkins may not restart, so the grants are rewritten."
    fi

    case "$_repo" in
        ''|'-'|'new') ;;
        # config.xml, not the directory. Jenkins holds every job in memory and
        # writes a skeleton back the moment one is removed from disk, so a bare
        # directory proves nothing: item 50 is the whole story. Measured here
        # on 2026-09-04, where a folder moved aside reappeared within seconds
        # carrying nothing but jobs/.
        *) if [ ! -f "$JENKINS_JOBS_DIR/$_n/config.xml" ]; then
               NEED_JOBS=1
               print_info "$_n names a repository and has no Jenkins folder, so the jobs are written."
           fi ;;
    esac
done < <(conf_rows)


# Folders whose row has gone. Same test add_jenkins_site_jobs.sh uses, so this
# cannot ask it to run over a folder it would refuse to touch: the generated
# mark, or no config.xml at all, which is the skeleton a running Jenkins writes
# back after a prune (item 50).
#
# Only with --prune, because reporting an orphan it is not allowed to delete
# would put a line in every apply that nobody can act on.
JENKINS_MARK="<!-- generated by add_jenkins_site_jobs.sh, safe to prune -->"
if [ "$PRUNE" -eq 1 ] && [ -d "$JENKINS_JOBS_DIR" ]; then
    for _dir in "$JENKINS_JOBS_DIR"/*/; do
        [ -d "$_dir" ] || continue
        _folder="$(basename "$_dir")"
        if [ ! -f "$_dir/config.xml" ]; then
            NEED_JOBS=1
            print_info "Jenkins folder '$_folder' has no config.xml, so the job generator is run to clear it."
            continue
        fi
        grep -qF "$JENKINS_MARK" "$_dir/config.xml" 2>/dev/null || continue
        _isrow=0
        while IFS='|' read -r _rt _rn _rrest; do
            _rn="$(printf '%s' "$_rn" | tr -d ' \r')"
            case "$_rt" in *=*) continue ;; esac
            [ "$_rn" = "$_folder" ] && { _isrow=1; break; }
        done < <(conf_rows)
        if [ "$_isrow" -eq 0 ]; then
            NEED_JOBS=1
            print_info "Jenkins folder '$_folder' has no row in the config, so it is pruned."
        fi
    done
fi

